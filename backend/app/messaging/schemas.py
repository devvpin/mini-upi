"""
messaging.schemas — Data transfer objects for Client, PSP, Switch, and Bank inter-module calls.

Crypto concept: Canonical serialization contracts for cross-party message signing and MAC verification.
Threat mitigated: Inter-service message tampering, impersonation, structural deserialization mismatch.
"""

from __future__ import annotations

from typing import Any
from pydantic import BaseModel, Field


class PaymentPayload(BaseModel):
    """The canonical transaction authorization payload signed by the device."""

    txn_id: str = Field(..., description="Unique transaction UUID generated by client")
    payer_vpa: str = Field(..., description="Virtual Payment Address of remitter")
    payee_vpa: str = Field(..., description="Virtual Payment Address of beneficiary")
    amount_paise: int = Field(..., ge=100, description="Amount in virtual paise (min 100 = ₹1)")
    note: str | None = Field(default=None, max_length=200, description="Payment remark")
    nonce: str = Field(..., min_length=8, max_length=128, description="Anti-replay random nonce")
    ts: int = Field(..., description="Unix epoch timestamp in seconds")


class InnerPaymentRequest(BaseModel):
    """Inner payload contained inside the client's envelope encryption."""

    payload: PaymentPayload
    device_sig: str = Field(..., description="Base64 raw 64-byte ECDSA P-256 signature by device key")
    mpin: str = Field(..., min_length=4, max_length=6, description="User's numeric MPIN")


class PspToSwitchMessage(BaseModel):
    """Message routed from PSP to Switch with PSP certificate and signature."""

    payload: PaymentPayload
    psp_id: str
    psp_cert_pem: str
    psp_signature: str
    psp_ts: int


class SwitchToBankMessage(BaseModel):
    """Message passed from Switch to Bank authenticated with HMAC service MAC."""

    payload: PaymentPayload
    payer_account_id: str
    payee_account_id: str
    switch_id: str
    ts: int
    key_id: str
    mac: str


class BankReceipt(BaseModel):
    """Cryptographic payment receipt signed by the Bank."""

    txn_id: str
    payer_vpa: str
    payee_vpa: str
    amount_paise: int
    note: str | None = None
    status: str = "SUCCESS"
    completed_at: str
    bank_cert_pem: str
    bank_signature: str
    chain_seq: int
    chain_hash: str

    def to_dict(self) -> dict[str, Any]:
        return self.model_dump()
